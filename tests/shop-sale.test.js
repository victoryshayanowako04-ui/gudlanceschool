const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const app = fs.readFileSync(path.join(root, "app.js"), "utf8");
const migration = fs.readFileSync(
  path.join(root, "supabase/migrations/20261124210000_atomic_shop_sale.sql"),
  "utf8"
);

function shopSaleSource() {
  const start = app.indexOf("window.processShopSale = async function()");
  const end = app.indexOf("window.autoFillShopPayment = function()", start);
  assert.notEqual(start, -1, "shop sale handler must exist");
  assert.notEqual(end, -1, "shop sale handler boundary must exist");
  return app.slice(start, end);
}

test("shop sales persist through the single atomic database function", () => {
  const source = shopSaleSource();
  assert.match(source, /\.rpc\(\s*["']process_shop_sale["']/);
  assert.doesNotMatch(source, /\.from\(["']inventory["']\)\s*\.update\(/);
  assert.doesNotMatch(source, /\.from\(["']transactions["']\)\s*\.insert\(/);
  assert.doesNotMatch(source, /\.from\(["']student_ledger["']\)\s*\.insert\(/);
  assert.doesNotMatch(source, /\.from\(["']payments["']\)\s*\.insert\(/);
});

test("walk-in payment rows are handled by the database function without a fake student FK", () => {
  assert.match(migration, /IF v_student_id = 'WALK-IN' THEN[\s\S]*?jsonb_set\(v_payment_row, '\{student_id\}', 'null'::jsonb/);
  assert.match(migration, /NULLIF\(v_payment_row->>'student_id', 'null'\)/);
});

test("concurrent stock sales lock inventory and reject insufficient quantities", () => {
  assert.match(migration, /FOR UPDATE/);
  assert.match(migration, /COALESCE\(qty, 0\) >= v_item\.quantity/);
  assert.match(migration, /pg_advisory_xact_lock/);
});

test("student credit is checked against the latest ledger and included in the sale payment ledger", () => {
  assert.match(migration, /v_available_credit := GREATEST\(0, -v_new_balance\)/);
  assert.match(migration, /v_ledger->>'amount'\)::numeric, 0\) \+ p_credit_applied/);
  assert.match(migration, /'charge', 'fee'/);
  assert.match(migration, /'payment', 'discount', 'waiver', 'credit', 'overpayment'/);
});

test("payment IDs are generated by a database sequence, not client timestamps", () => {
  assert.match(migration, /ALTER COLUMN id SET DEFAULT nextval\('public\.payments_id_seq'\)/);
  assert.doesNotMatch(shopSaleSource(), /id:\s*Math\.floor\(Date\.now\(\)\s*\/\s*1000\)/);
});

test("fee payment RPC serializes student updates and uses collision-resistant IDs", () => {
  const feeMigration = fs.readFileSync(
    path.join(root, "supabase/migrations/20261124213000_serialize_fee_payments_and_balance.sql"),
    "utf8"
  );
  assert.match(feeMigration, /FOR UPDATE/);
  assert.match(feeMigration, /nextval\('public\.payment_receipt_seq'\)/);
  assert.match(feeMigration, /gen_random_uuid\(\)/);
  assert.match(feeMigration, /SET balance_owing = public\.get_student_balance/);
});

test("database balance function matches the app ledger categories and void rules", () => {
  const feeMigration = fs.readFileSync(
    path.join(root, "supabase/migrations/20261124213000_serialize_fee_payments_and_balance.sql"),
    "utf8"
  );
  for (const type of ["charge", "fee", "payment", "discount", "waiver", "credit", "overpayment"]) {
    assert.ok(feeMigration.includes("'" + type + "'"), "balance function must include " + type);
  }
  assert.match(feeMigration, /NOT IN \('VOID', 'VOIDED', 'REVERSAL'\)/);
});

